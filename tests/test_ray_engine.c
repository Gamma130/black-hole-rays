#define EPS 1e-2

int almost_equal(double a, double b)
{
    return fabs(a - b) <= EPS * fmax(1.0, fmax(fabs(a), fabs(b)));
}

int compare_output(int px,
                   double output[px][px][8],
                   double expected[px][px][8])
{
    int failures = 0;

    for(int i = 0; i < px; i++)
    {
        for(int j = 0; j < px; j++)
        {
            for(int k = 0; k < 8; k++)
            {
                if(!almost_equal(output[i][j][k],
                                 expected[i][j][k]))
                {
                    printf("Mismatch at [%d][%d][%d]\n", i, j, k);
                    printf("Got:      %.15f\n", output[i][j][k]);
                    printf("Expected: %.15f\n\n", expected[i][j][k]);

                    failures++;
                }
            }
        }
    }

    if(failures == 0)
    {
        printf("All values match within tolerance\n");
        return 1;
    }

    printf("Total mismatches: %d\n", failures);
    return 0;
}

